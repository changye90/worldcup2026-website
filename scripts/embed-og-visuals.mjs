#!/usr/bin/env node
/**
 * Embed hero JPEG + flag PNG sprites for OG SVG (Cloudflare Workers, no fetch).
 * Run: node scripts/embed-og-visuals.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const heroSrc = path.join(root, 'public/hero.png');
const matchesPath = path.join(root, 'functions/data/matches-og.json');
const teamFlagsPath = path.join(root, 'functions/data/team-flags.json');
const tmpDir = path.join(root, '.og-embed-tmp');

function b64(file) {
  return fs.readFileSync(file).toString('base64');
}

function collectFlagEmojis() {
  const emojis = new Set();
  const matches = JSON.parse(fs.readFileSync(matchesPath, 'utf8'));
  for (const m of matches) {
    if (m.flag1) emojis.add(m.flag1);
    if (m.flag2) emojis.add(m.flag2);
  }
  const tf = JSON.parse(fs.readFileSync(teamFlagsPath, 'utf8'));
  for (const flag of Object.values(tf.teams || {})) emojis.add(flag);
  for (const flag of Object.values(tf.countries || {})) emojis.add(flag);
  emojis.delete('⚽');
  emojis.delete('🏳️');
  emojis.delete('🏳');
  return [...emojis];
}

/** @param {string} flag */
function flagEmojiToIso(flag) {
  const SPECIAL = {
    '🏴󠁧󠁢󠁳󠁣󠁴󠁿': 'gb-sct',
    '🏴󠁧󠁢󠁥󠁮󠁧󠁿': 'gb-eng',
  };
  const f = flag.trim();
  if (SPECIAL[f]) return SPECIAL[f];
  const chars = [...f];
  const a = chars[0]?.codePointAt(0);
  const b = chars[1]?.codePointAt(0);
  if (
    a != null &&
    b != null &&
    a >= 0x1f1e6 &&
    a <= 0x1f1ff &&
    b >= 0x1f1e6 &&
    b <= 0x1f1ff
  ) {
    return (
      String.fromCharCode(a - 0x1f1e6 + 0x41) + String.fromCharCode(b - 0x1f1e6 + 0x41)
    ).toLowerCase();
  }
  return null;
}

function buildHeroJpeg() {
  if (!fs.existsSync(heroSrc)) {
    console.warn('No', heroSrc);
    return '';
  }
  fs.mkdirSync(tmpDir, { recursive: true });
  const out = path.join(tmpDir, 'hero-og.jpg');
  try {
    execSync(
      `sips -s format jpeg -s formatOptions 58 --resampleWidth 1200 "${heroSrc}" --out "${out}"`,
      { stdio: 'pipe' },
    );
    const meta = execSync(`sips -g pixelHeight -g pixelWidth "${out}"`, { encoding: 'utf8' });
    const h = Number(meta.match(/pixelHeight: (\d+)/)?.[1] || 0);
    const w = Number(meta.match(/pixelWidth: (\d+)/)?.[1] || 0);
    if (h > 630) {
      const cropY = Math.max(0, Math.floor((h - 630) / 2));
      execSync(
        `sips -c 630 1200 --cropOffset 0 ${cropY} "${out}" --out "${out}"`,
        { stdio: 'pipe' },
      );
    }
  } catch (e) {
    console.error('sips failed — copy hero.png as-is base64 may be huge:', e.message);
    return '';
  }
  const jpegB64 = b64(out);
  console.log('hero JPEG', Math.round(jpegB64.length * 0.75 / 1024), 'KB');
  return `data:image/jpeg;base64,${jpegB64}`;
}

async function fetchFlagSprites() {
  const emojis = collectFlagEmojis();
  const isoSet = new Set();
  for (const e of emojis) {
    const iso = flagEmojiToIso(e);
    if (iso) isoSet.add(iso);
  }
  fs.mkdirSync(tmpDir, { recursive: true });
  const sprites = {};
  for (const iso of [...isoSet].sort()) {
    const url = `https://flagcdn.com/w80/${iso}.png`;
    const res = await fetch(url);
    if (!res.ok) {
      console.warn('skip flag', iso, res.status);
      continue;
    }
    const buf = Buffer.from(await res.arrayBuffer());
    const file = path.join(tmpDir, `${iso}.png`);
    fs.writeFileSync(file, buf);
    sprites[iso] = `data:image/png;base64,${buf.toString('base64')}`;
    console.log('flag', iso, buf.length, 'bytes');
  }
  return sprites;
}

function writeTs(heroDataUrl, sprites) {
  const heroEsc = heroDataUrl.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  const heroTs = `/** Generated by scripts/embed-og-visuals.mjs — do not edit. */
const HERO = '${heroEsc}';

export function getOgHeroJpegDataUrl(): string {
  return HERO;
}
`;
  fs.writeFileSync(path.join(root, 'functions/ogHeroBg.ts'), heroTs);

  const entries = Object.entries(sprites)
    .map(([iso, url]) => `  '${iso}': '${url.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`)
    .join('\n');
  const flagTs = `/** Generated by scripts/embed-og-visuals.mjs — do not edit. */
const SPRITES: Record<string, string> = {
${entries}
};

export function getOgFlagSpriteDataUrl(iso: string): string | undefined {
  return SPRITES[iso.toLowerCase()];
}
`;
  fs.writeFileSync(path.join(root, 'functions/ogFlagSprites.ts'), flagTs);
  console.log('Wrote functions/ogHeroBg.ts + functions/ogFlagSprites.ts', Object.keys(sprites).length, 'flags');
}

const heroDataUrl = buildHeroJpeg();
const sprites = await fetchFlagSprites();
writeTs(heroDataUrl, sprites);
