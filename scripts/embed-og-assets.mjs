#!/usr/bin/env node
/** Embed Inter TTF + fallback PNG for Cloudflare Functions (no HTTP fetch). */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const fontsDir = path.join(root, 'public/fonts');
const fallbackPng = path.join(root, 'public/og-ticket-fallback.png');

function b64(file) {
  return fs.readFileSync(file).toString('base64');
}

const inter400 = path.join(fontsDir, 'inter-latin-400-normal.ttf');
const inter700 = path.join(fontsDir, 'inter-latin-700-normal.ttf');
if (!fs.existsSync(inter400)) {
  console.error('Missing', inter400);
  process.exit(1);
}
if (!fs.existsSync(inter700)) {
  console.error('Missing', inter700);
  process.exit(1);
}

const fontBuffersTs = `/** Generated by npm run embed:og-assets — do not edit. */
const B64_400 = '${b64(inter400)}';
const B64_700 = '${b64(inter700)}';

function decode(b64: string): Uint8Array {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

let cached: Uint8Array[] | null = null;

/** Lazy decode so module load stays fast on Cloudflare Workers. */
export function getOgFontBuffers(): Uint8Array[] {
  if (!cached) {
    cached = [decode(B64_400), decode(B64_700)];
  }
  return cached;
}
`;

fs.writeFileSync(path.join(root, 'functions/ogFontBuffers.ts'), fontBuffersTs);

let pngB64 = '';
if (fs.existsSync(fallbackPng)) {
  pngB64 = b64(fallbackPng);
} else {
  console.warn('No', fallbackPng);
}

const fallbackTs = `/** Generated by npm run embed:og-assets — do not edit. */
const B64 = '${pngB64}';

function decode(b64: string): Uint8Array {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

let cached: Uint8Array | null = null;

export function getOgFallbackPng(): Uint8Array {
  if (!cached) cached = decode(B64);
  return cached;
}
`;

fs.writeFileSync(path.join(root, 'functions/ogFallbackPng.ts'), fallbackTs);
console.log('Wrote functions/ogFontBuffers.ts + functions/ogFallbackPng.ts');
