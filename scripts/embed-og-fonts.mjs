#!/usr/bin/env node
/** Bundle Inter TTF into functions/ogFontBuffers.ts for Cloudflare (no HTTP fetch). */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const fontsDir = path.join(root, 'functions/fonts');
const out = path.join(root, 'functions/ogFontBuffers.ts');

function b64(file) {
  return fs.readFileSync(path.join(fontsDir, file)).toString('base64');
}

const body = `/** Generated by npm run embed:og-fonts — do not edit. */
function decode(b64: string): Uint8Array {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

export const OG_FONT_BUFFERS: Uint8Array[] = [
  decode('${b64('inter-latin-400-normal.ttf')}'),
  decode('${b64('inter-latin-700-normal.ttf')}'),
];
`;

fs.writeFileSync(out, body);
console.log('Wrote', out, `(${Math.round(body.length / 1024)} KB)`);
